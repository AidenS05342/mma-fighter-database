const state = {
  query: "",
  division: "All",
  sort: "wins",
  compareA: null,
  compareB: null,
};

function renderChips() {
  const present = DIVISION_ORDER.filter((d) => FIGHTERS.some((f) => f.division === d));
  const chips = ["All", ...present]
    .map((d) => {
      const n = d === "All" ? FIGHTERS.length : FIGHTERS.filter((f) => f.division === d).length;
      return `<button type="button" class="chip" data-division="${esc(d)}" aria-pressed="${d === state.division}">
                ${esc(d === "All" ? "All Divisions" : d)}<span class="count">${n}</span>
              </button>`;
    })
    .join("");
  $("#divisionChips").innerHTML = chips;
}

function getFilteredFighters() {
  const q = state.query.trim().toLowerCase();
  let list = FIGHTERS.filter((f) => {
    const matchesDivision = state.division === "All" || f.division === state.division;
    if (!matchesDivision) return false;
    if (!q) return true;
    return [f.name, f.nickname, f.nationality, f.countryCode, f.division, f.style, f.birthplace, f.status]
      .some((field) => field && field.toLowerCase().includes(q));
  });

  const sorters = {
    wins: (a, b) => sortVal(b.wins) - sortVal(a.wins) || sortVal(winPct(b)) - sortVal(winPct(a)),
    winPct: (a, b) => sortVal(winPct(b)) - sortVal(winPct(a)) || sortVal(b.wins) - sortVal(a.wins),
    finishes: (a, b) => sortVal(finishes(b)) - sortVal(finishes(a)) || sortVal(b.wins) - sortVal(a.wins),
    name: (a, b) => a.name.localeCompare(b.name),
  };
  return list.sort(sorters[state.sort]);
}

function renderDirectory() {
  const list = getFilteredFighters();
  $("#directoryGrid").innerHTML = list.map(fighterCard).join("");
  $("#emptyState").hidden = list.length > 0;

  const scope = state.division === "All" ? "all divisions" : state.division;
  $("#resultsCount").innerHTML =
    `Showing <strong>${list.length}</strong> of ${FIGHTERS.length} fighters in ${esc(scope)}` +
    (state.query ? ` matching "<strong>${esc(state.query)}</strong>"` : "");
}

function initDirectory() {
  renderChips();
  renderDirectory();

  let debounce;
  $("#searchInput").addEventListener("input", (e) => {
    clearTimeout(debounce);
    debounce = setTimeout(() => {
      state.query = e.target.value;
      renderDirectory();
    }, 120);
  });

  $("#sortSelect").addEventListener("change", (e) => {
    state.sort = e.target.value;
    renderDirectory();
  });

  $("#divisionChips").addEventListener("click", (e) => {
    const chip = e.target.closest(".chip");
    if (!chip) return;
    state.division = chip.dataset.division;
    $$(".chip").forEach((c) => c.setAttribute("aria-pressed", c === chip));
    renderDirectory();
  });

  $("#resetFilters").addEventListener("click", () => {
    state.query = "";
    state.division = "All";
    $("#searchInput").value = "";
    renderChips();
    renderDirectory();
    $("#searchInput").focus();
  });
}

