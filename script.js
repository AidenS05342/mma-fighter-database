function methodBar(f) {
  if (!f.methodsVerified) {
    return `<div class="method-bar" role="img" aria-label="Win methods not available"></div>`;
  }
  const w = f.wins || 1;
  return `
    <div class="method-bar" role="img" aria-label="Win methods: ${f.koWins} KO/TKO, ${f.subWins} submissions, ${f.decWins} decisions">
      <span class="m-ko" style="width:${(f.koWins / w) * 100}%"></span>
      <span class="m-sub" style="width:${(f.subWins / w) * 100}%"></span>
      <span class="m-dec" style="width:${(f.decWins / w) * 100}%"></span>
    </div>`;
}

function methodLegend(f) {
  return `
    <div class="method-legend">
      <div><b>${count(f.koWins)}</b><small><i class="m-ko"></i>KO/TKO</small></div>
      <div><b>${count(f.subWins)}</b><small><i class="m-sub"></i>Sub</small></div>
      <div><b>${count(f.decWins)}</b><small><i class="m-dec"></i>Dec</small></div>
    </div>`;
}

