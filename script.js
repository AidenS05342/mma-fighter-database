function renderHeroStats() {
  const divisions = new Set(FIGHTERS.map((f) => f.division)).size;
  const wins = FIGHTERS.reduce((s, f) => s + (isNum(f.wins) ? f.wins : 0), 0);
  const fin = FIGHTERS.reduce((s, f) => s + (finishes(f) ?? 0), 0);
  const values = [FIGHTERS.length, divisions, wins, fin];

  $$("#heroStats dd").forEach((dd, i) => animateCount(dd, values[i]));
}

function renderDataNote() {
  const el = $("#dataNote");
  if (!el) return;
  const unverified = FIGHTERS.filter((f) => !f.methodsVerified).length;
  el.textContent =
    `Real fighter data from UFC.com athlete profiles and the UFC Record Book` +
    (META.lastVerified ? `, last verified ${META.lastVerified}` : "") +
    `. Values UFC.com does not list are shown as N/A.` +
    (unverified ? ` Finish totals exclude ${unverified} fighter${unverified > 1 ? "s" : ""} whose win methods could not be verified.` : "");
}

function animateCount(el, target) {
  const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  if (reduce) {
    el.textContent = target;
    return;
  }
  const duration = 1100;
  const start = performance.now();
  const tick = (now) => {
    const t = Math.min((now - start) / duration, 1);
    const eased = 1 - Math.pow(1 - t, 3);
    el.textContent = Math.round(target * eased);
    if (t < 1) requestAnimationFrame(tick);
  };
  requestAnimationFrame(tick);
}

function renderFeatured() {
  const featured = FIGHTERS.filter((f) => f.featured);
  $("#featuredGrid").innerHTML = featured.map(fighterCard).join("");
}

