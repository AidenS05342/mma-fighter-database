// Age in whole years from an ISO birth date printed on UFC.com (null if unknown)
function ageFrom(iso) {
  if (!iso) return null;
  const b = new Date(iso + "T00:00:00");
  if (Number.isNaN(b.getTime())) return null;
  const now = new Date();
  let age = now.getFullYear() - b.getFullYear();
  if (now.getMonth() < b.getMonth() || (now.getMonth() === b.getMonth() && now.getDate() < b.getDate())) age--;
  return age;
}

// Flatten the generated record into the shape the UI uses.
// Win-method counts are only kept when UFC.com's counts add up to the listed wins;
// otherwise they cannot be verified and are shown as N/A.
const FIGHTERS = (DATA.fighters || []).map((r) => {
  const ok = r.methodsComplete === true;
  const u = r.ufc || {};
  return {
    id: r.id,
    name: r.name,
    nickname: r.nickname || null,
    status: r.status || null,
    nationality: r.nationality || null,
    countryCode: r.countryCode || null,
    birthplace: r.birthplace || null,
    division: r.division || "Unlisted",
    featured: !!r.featured,
    wins: r.wins ?? null,
    losses: r.losses ?? null,
    draws: r.draws ?? null,
    koWins: ok ? r.koWins : null,
    subWins: ok ? r.subWins : null,
    decWins: ok ? r.decWins : null,
    methodsVerified: ok,
    age: ageFrom(r.birthDate),
    height: r.height ?? null,
    reach: r.reach ?? null,
    style: r.fightingStyle || null,
    debut: r.octagonDebut || null,
    slpm: u.slpm ?? null,
    sapm: u.sapm ?? null,
    strAcc: u.strAcc ?? null,
    strDef: u.strDef ?? null,
    tdAvg: u.tdAvg ?? null,
    tdAcc: u.tdAcc ?? null,
    tdDef: u.tdDef ?? null,
    subAvg: u.subAvg ?? null,
    kdAvg: u.kdAvg ?? null,
    avgFightTime: u.avgFightTime || null,
    recordBook: Array.isArray(r.recordBook) ? r.recordBook : [],
    sourceUrl: r.sourceUrl,
    fetchedAt: r.fetchedAt,
  };
});

// Display order for divisions (heaviest to lightest, men then women)
const DIVISION_ORDER = [
  "Heavyweight",
  "Light Heavyweight",
  "Middleweight",
  "Welterweight",
  "Lightweight",
  "Featherweight",
  "Bantamweight",
  "Flyweight",
  "Women's Featherweight",
  "Women's Bantamweight",
  "Women's Flyweight",
  "Women's Strawweight",
];
// Any division in the data that is not listed above goes at the end
FIGHTERS.forEach((f) => {
  if (!DIVISION_ORDER.includes(f.division)) DIVISION_ORDER.push(f.division);
});

/* ---------------------------------------------------------
   2. HELPERS
   --------------------------------------------------------- */
const $ = (sel, root = document) => root.querySelector(sel);
const $$ = (sel, root = document) => [...root.querySelectorAll(sel)];

const byId = new Map(FIGHTERS.map((f) => [f.id, f]));

const isNum = (v) => typeof v === "number" && Number.isFinite(v);
const hasRecord = (f) => isNum(f.wins) && isNum(f.losses) && isNum(f.draws);
const totalFights = (f) => (hasRecord(f) ? f.wins + f.losses + f.draws : null);
const winPct = (f) => (totalFights(f) ? (f.wins / totalFights(f)) * 100 : null);
const finishes = (f) => (f.methodsVerified ? f.koWins + f.subWins : null);
const finishRate = (f) => (f.methodsVerified && f.wins ? (finishes(f) / f.wins) * 100 : null);
const recordStr = (f) => (hasRecord(f) ? `${f.wins}-${f.losses}-${f.draws}` : NA);
const pct = (n) => (isNum(n) ? `${Math.round(n)}%` : NA);
const fixed = (d) => (n) => (isNum(n) ? n.toFixed(d) : NA);
const count = (n) => (isNum(n) ? String(n) : NA);
const text = (s) => (s ? s : NA);
const initials = (name) =>
  name
    .split(/[\s-]+/)
    .map((p) => p[0])
    .join("")
    .slice(0, 2)
    .toUpperCase();
const inchesToFtIn = (inches) => {
  if (!isNum(inches)) return NA;
  const rest = Math.round((inches % 12) * 10) / 10;
  return `${Math.floor(inches / 12)}'${rest}"`;
};
const inches = (n) => (isNum(n) ? `${n}"` : NA);
const sortVal = (v) => (isNum(v) ? v : -1); // unknown values sort last

// Escape any text inserted into HTML templates
const esc = (str) =>
  String(str ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

const nickHtml = (f) => (f.nickname ? `"${esc(f.nickname)}"` : "&nbsp;");
const countryBadge = (f) =>
  f.nationality ? `${esc(f.countryCode || NA)} · ${esc(f.nationality)}` : `Country ${NA}`;

